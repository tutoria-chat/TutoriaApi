using System.Data.Common;
using Microsoft.EntityFrameworkCore;
using Microsoft.Extensions.Configuration;

namespace TutoriaApi.Infrastructure.Data;

/// <summary>
/// The Postgres tables that replace DynamoDB and SQS (tutoria-api docs/MULTICLOUD.md):
/// "ChatHistory" (ChatStore=postgres), "QuizAttemptAnswers", and "WorkerJobs"
/// (Jobs:Queue=postgres). They are shared with tutoria-api and tutoria-worker, so they
/// are not EF entities: every service runs the same DDL at startup under one advisory
/// lock. Keep <see cref="Ddl"/> identical to tutoria-api app/stores/schema.py.
/// </summary>
public static class PostgresStores
{
    public const string ChatStoreKey = "ChatStore";
    public const string JobQueueKey = "Jobs:Queue";

    /// <summary>Same id as tutoria-api and tutoria-worker.</summary>
    public const long SchemaLock = 734_331_001;

    public static bool ChatInPostgres(IConfiguration configuration) =>
        Choice(configuration, ChatStoreKey, "dynamodb", "postgres") == "postgres";

    public static bool JobsInPostgres(IConfiguration configuration) =>
        Choice(configuration, JobQueueKey, "sqs", "postgres") == "postgres";

    /// <summary>The value, lower-cased; an unknown one refuses (a typo must not fall back to AWS).</summary>
    public static string Choice(IConfiguration configuration, string key, string defaultValue, string other)
    {
        var value = (configuration[key] ?? defaultValue).Trim().ToLowerInvariant();
        if (value.Length == 0) value = defaultValue;
        if (value != defaultValue && value != other)
            throw new InvalidOperationException($"{key} must be '{defaultValue}' or '{other}', is '{value}'");
        return value;
    }

    public static readonly string[] Ddl =
    {
        """
        CREATE TABLE IF NOT EXISTS "ChatHistory" (
            "Id"             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            "ConversationId" varchar(200) NOT NULL,
            "Ts"             bigint       NOT NULL,
            "MessageId"      varchar(64)  NOT NULL,
            "StudentId"      integer      NOT NULL DEFAULT 0,
            "ModuleId"       integer      NOT NULL DEFAULT 0,
            "Question"       text         NOT NULL DEFAULT '',
            "Response"       text         NOT NULL DEFAULT '',
            "ModelUsed"      varchar(200),
            "Provider"       varchar(100),
            "HasFile"        boolean      NOT NULL DEFAULT false,
            "FileName"       varchar(500),
            "TokenCount"     integer,
            "ResponseTime"   integer,
            "Matricula"      varchar(100),
            "CreatedAt"      timestamptz  NOT NULL DEFAULT now(),
            "ExpiresAt"      timestamptz  NOT NULL
        )
        """,
        """CREATE INDEX IF NOT EXISTS "IX_ChatHistory_Conversation" ON "ChatHistory" ("ConversationId", "Ts")""",
        """CREATE INDEX IF NOT EXISTS "IX_ChatHistory_Student" ON "ChatHistory" ("StudentId", "Ts")""",
        """CREATE INDEX IF NOT EXISTS "IX_ChatHistory_Module" ON "ChatHistory" ("ModuleId", "Ts")""",
        """CREATE INDEX IF NOT EXISTS "IX_ChatHistory_Provider" ON "ChatHistory" ("Provider", "Ts")""",
        """CREATE INDEX IF NOT EXISTS "IX_ChatHistory_ExpiresAt" ON "ChatHistory" ("ExpiresAt")""",
        """
        CREATE TABLE IF NOT EXISTS "QuizAttemptAnswers" (
            "Id"              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            "AttemptId"       varchar(64)  NOT NULL,
            "ModuleId"        integer      NOT NULL,
            "Ts"              bigint       NOT NULL,
            "StudentId"       integer      NOT NULL DEFAULT 0,
            "QuizId"          integer,
            "QuestionNumber"  integer      NOT NULL DEFAULT 0,
            "SelectedAnswer"  text         NOT NULL DEFAULT '',
            "CorrectAnswer"   text         NOT NULL DEFAULT '',
            "IsCorrect"       boolean      NOT NULL DEFAULT false,
            "ConceptsCovered" text         NOT NULL DEFAULT '',
            "Difficulty"      varchar(30)  NOT NULL DEFAULT 'medium',
            "CreatedAt"       timestamptz  NOT NULL DEFAULT now(),
            "ExpiresAt"       timestamptz  NOT NULL
        )
        """,
        """CREATE INDEX IF NOT EXISTS "IX_QuizAttemptAnswers_Student" ON "QuizAttemptAnswers" ("StudentId", "Ts")""",
        """CREATE INDEX IF NOT EXISTS "IX_QuizAttemptAnswers_Module" ON "QuizAttemptAnswers" ("ModuleId", "Ts")""",
        """CREATE INDEX IF NOT EXISTS "IX_QuizAttemptAnswers_ExpiresAt" ON "QuizAttemptAnswers" ("ExpiresAt")""",
        """
        CREATE TABLE IF NOT EXISTS "WorkerJobs" (
            "Id"          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            "Kind"        varchar(30)  NOT NULL,
            "Payload"     text,
            "State"       varchar(20)  NOT NULL DEFAULT 'queued',
            "Attempts"    integer      NOT NULL DEFAULT 0,
            "AvailableAt" timestamptz  NOT NULL DEFAULT now(),
            "CreatedAt"   timestamptz  NOT NULL DEFAULT now(),
            "ClaimedBy"   varchar(100),
            "ClaimedAt"   timestamptz,
            "LeaseUntil"  timestamptz,
            "FinishedAt"  timestamptz,
            "LastError"   varchar(1000)
        )
        """,
        """CREATE INDEX IF NOT EXISTS "IX_WorkerJobs_Waiting" ON "WorkerJobs" ("AvailableAt") WHERE "State" IN ('queued', 'processing')""",
        """CREATE INDEX IF NOT EXISTS "IX_WorkerJobs_Finished" ON "WorkerJobs" ("FinishedAt") WHERE "FinishedAt" IS NOT NULL""",
    };

    /// <summary>Creates whatever is missing, in one transaction under the shared lock.</summary>
    public static async Task EnsureSchemaAsync(TutoriaDbContext db, CancellationToken ct = default)
    {
        await using var tx = await db.Database.BeginTransactionAsync(ct);
        await db.Database.ExecuteSqlRawAsync($"SELECT pg_advisory_xact_lock({SchemaLock})", ct);
        foreach (var statement in Ddl)
            await db.Database.ExecuteSqlRawAsync(statement, ct);
        await tx.CommitAsync(ct);
    }

    /// <summary>A job for tutoria-worker: the same JSON the SQS message carried.</summary>
    public static Task<int> EnqueueJobAsync(TutoriaDbContext db, string kind, string payloadJson, CancellationToken ct = default) =>
        db.Database.ExecuteSqlInterpolatedAsync(
            $"""INSERT INTO "WorkerJobs" ("Kind", "Payload") VALUES ({kind}, {payloadJson})""", ct);

    /// <summary>An open connection of the context (opened here when it was closed).</summary>
    public static async Task<DbConnection> OpenConnectionAsync(TutoriaDbContext db, CancellationToken ct = default)
    {
        var connection = db.Database.GetDbConnection();
        if (connection.State != System.Data.ConnectionState.Open)
            await connection.OpenAsync(ct);
        return connection;
    }
}
